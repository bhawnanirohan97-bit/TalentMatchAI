function stageEvent(
  appId: string,
  from: Application["status"],
  to: Application["status"],
  daysAgo: number,
  actor = ACTOR_RECRUITER,
  note?: string,
): ApplicationStageEvent {
  return {
    id: `evt-${appId}-${to.toLowerCase().replace(/\s/g, "-")}`,
    applicationId: appId,
    from,
    to,
    actorId: actor.id,
    actorName: actor.name,
    note,
    createdAt: daysAgoIso(daysAgo),
  };
}

