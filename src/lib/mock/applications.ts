function buildApplication(
  id: string,
  candidateId: string,
  candidateName: string,
  jobId: string,
  jobTitle: string,
  companyId: string,
  companyName: string,
  resumeId: string,
  resumeFileName: string,
  status: Application["status"],
  matchScore: number,
  appliedDaysAgo: number,
  source = "portal",
): Application {
  return {
    id,
    candidateId,
    candidateName,
    jobId,
    jobTitle,
    companyId,
    companyName,
    resumeId,
    resumeFileName,
    coverLetter: "",
    status,
    matchScore,
    source,
    createdAt: daysAgoIso(appliedDaysAgo),
    updatedAt: daysAgoIso(Math.max(0, appliedDaysAgo - 2)),
  };
}

